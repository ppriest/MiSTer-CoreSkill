"""Write the tool reference from the server's own tools/list: tools.json (the MCP form, JSON Schema
per tool) and TOOLS.md (the same, readable). Run after changing a tool:

    .venv/Scripts/python.exe gen_docs.py
"""
import asyncio
import json
from pathlib import Path

from mister_mcp.server import server

HERE = Path(__file__).resolve().parent
GROUPS = [("jobs", "Jobs and locks", ("cores_", "jobs_", "locks_")), ("build", "Builds", ("build_",)),
          ("sim", "Simulation", ("sim_",)), ("mame", "MAME", ("mame_",)),
          ("mister", "MiSTer", ("mister_",)), ("probe", "Probes (JTAG)", ("probe_",))]


def type_of(p):
    if "anyOf" in p:
        return " or ".join(type_of(x) for x in p["anyOf"])
    t = p.get("type", "any")
    if t == "array":
        return f"list[{type_of(p.get('items', {}))}]"
    if t == "object" and "additionalProperties" in p:
        return f"dict[str, {type_of(p['additionalProperties'])}]"
    return t


def hint(t):
    a = t.annotations
    if not a:
        return ""
    if a.destructive_hint:
        return "destructive"
    return "read-only" if a.read_only_hint else "acts"


def main():
    tools = asyncio.run(server.list_tools())
    dump = [t.model_dump(by_alias=True, exclude_none=True, mode="json") for t in tools]
    (HERE / "tools.json").write_text(json.dumps(dump, indent=1) + "\n", encoding="utf-8")

    md = ["# mister_mcp tools", "",
          "Generated by `gen_docs.py` from the server's `tools/list`; do not edit by hand. "
          "The same data as JSON Schema is in `tools.json`.", ""]
    md += [f"- [{title}](#{key})" for key, title, _ in GROUPS] + [""]
    for key, title, prefixes in GROUPS:
        md += [f'<a id="{key}"></a>', f"## {title}", ""]
        for t in (t for t in tools if t.name.startswith(prefixes)):
            md += [f"### `{t.name}`", "", f"*{hint(t)}*", "", " ".join((t.description or "").split()), ""]
            props = t.input_schema.get("properties", {})
            req = set(t.input_schema.get("required", []))
            if props:
                md += ["| Argument | Type | Default |", "|---|---|---|"]
                for n, p in props.items():
                    d = "required" if n in req else f"`{json.dumps(p.get('default'))}`"
                    md.append(f"| `{n}` | {type_of(p)} | {d} |")
                md.append("")
    (HERE / "TOOLS.md").write_text("\n".join(md), encoding="utf-8")
    print(f"{len(tools)} tools -> tools.json, TOOLS.md")


if __name__ == "__main__":
    main()
